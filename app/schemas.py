"""Input and output contracts. Extend validators alongside the implementation."""

from pydantic import BaseModel, ConfigDict, Field, field_validator


class ProductInput(BaseModel):
    """Source data for a single product."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(description="Product name")
    manufacturer: str | None = None
    specs: dict[str, str] = Field(default_factory=dict)
    description: str | None = None

    @field_validator("name")
    @classmethod
    def name_must_not_be_blank(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("Название товара не должно быть пустым")
        return value

    @field_validator("manufacturer", "description")
    @classmethod
    def normalize_optional_text(cls, value: str | None) -> str | None:
        if value is None:
            return None
        return value.strip() or None

    @field_validator("specs")
    @classmethod
    def characteristic_names_must_not_be_blank(cls, value: dict[str, str]) -> dict[str, str]:
        if any(not name.strip() for name in value):
            raise ValueError("Название характеристики не должно быть пустым")
        return value

class Characteristic(BaseModel):
    """A source-backed characteristic copied from ProductInput.specs."""

    name: str = Field(min_length=1)
    value: str
    source: str = "specs"


class GeneratedCopy(BaseModel):
    """Only the text fields generated by the LLM; source facts stay application-owned."""

    model_config = ConfigDict(extra="forbid")

    seo_title: str
    seo_description: str
    search_queries: list[str]
    commercial_block: str


class ProductDraft(BaseModel):
    """Generated copy plus deterministic source-backed fields."""

    seo_title: str
    seo_description: str
    characteristics: list[Characteristic]
    search_queries: list[str]
    commercial_block: str
    missing_data: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)


class DraftResponse(BaseModel):
    """API wrapper carrying both machine-readable and copyable output."""

    draft: ProductDraft
    markdown: str
